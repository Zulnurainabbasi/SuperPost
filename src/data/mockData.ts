// Helper to calculate date offsets relative to today
const getRelativeDate = (dayOffset: number, hour: number = 14, minute: number = 30) => {
  const d = new Date();
  d.setDate(d.getDate() + dayOffset);
  d.setHours(hour, minute, 0, 0);
  return d.toISOString();
};

